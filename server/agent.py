def _db_key(conn: sqlite3.Connection) -> str:
    # Ключ — ПУТЬ базы, а не id(conn): id переиспользуется после GC, и memo
    # начинало врать (ensure пропускался на новой базе/новом соединении).
    # Пустой путь (чистый :memory:) — отдельная база на соединение.
    # PRAGMA транзакцию не открывает — безопасно в любом контексте.
    try:
        row = conn.execute("PRAGMA database_list").fetchone()
        if row and row[2]:
            return str(row[2])
        return f"memory:{id(conn)}"
    except sqlite3.Error:
        return f"memory:{id(conn)}"


# Внешний идентификатор треда: 10 символов [A-Za-z0-9] (~60 бит). 10 выбрано
# как в задаче: короткая ссылка, перебор при лимитах невозможен. Символы
# (-_~ и т.п.) не используем осознанно: в хэше #/ai/<ref> они требуют
# кодирования и ломаются при копипасте, а выигрыша к энтропии не дают.
THREAD_PUBLIC_ID_LEN = 10
THREAD_PUBLIC_ALPHABET = ("ABCDEFGHIJKLMNOPQRSTUVWXYZ"
                          "abcdefghijklmnopqrstuvwxyz0123456789")
THREAD_PUBLIC_ID_RE = re.compile(r"^[A-Za-z0-9]{10}$")


def generate_thread_public_id() -> str:
    return "".join(secrets.choice(THREAD_PUBLIC_ALPHABET)
                   for _ in range(THREAD_PUBLIC_ID_LEN))


def is_thread_public_ref(raw) -> bool:
    return isinstance(raw, str) and bool(THREAD_PUBLIC_ID_RE.match(raw))


def create_thread_row(conn: sqlite3.Connection, user_id: int, subject: str,
                      title: str = "Новый чат") -> tuple[int, str]:
    """Вставить тред с уникальным public_id. Возвращает (id, public_id)."""
    now_ms = int(time.time() * 1000)
    last_exc: Exception | None = None
    for _ in range(20):
        cand = generate_thread_public_id()
        try:
            cur = conn.execute("INSERT INTO agent_threads(user_id, subject, title,"
                               " created_at, updated_at, public_id)"
                               " VALUES(?,?,?,?,?,?)",
                               (int(user_id), subject, title, now_ms, now_ms, cand))
            conn.commit()
            return int(cur.lastrowid), cand
        except sqlite3.Error as exc:
            last_exc = exc
            try:
                conn.rollback()
            except sqlite3.Error:
                pass
            # Коллизия public_id (UNIQUE) — пробуем следующий; остальное наружу.
            if "public_id" not in str(exc).lower() and "unique" not in str(exc).lower():
                # Старая база без колонки: пишем по старой схеме без public_id.
                try:
                    cur = conn.execute("INSERT INTO agent_threads(user_id, subject, title,"
                                       " created_at, updated_at)"
                                       " VALUES(?,?,?,?,?)",
                                       (int(user_id), subject, title, now_ms, now_ms))
                    conn.commit()
                    return int(cur.lastrowid), ""
                except sqlite3.Error:
                    pass
                raise
            continue
    raise last_exc if last_exc is not None else RuntimeError("no thread id")


def empty_threads(conn: sqlite3.Connection, user_id: int) -> list:
    """Пустые чаты ученика (в которых нет НИ ОДНОГО сообщения), свежие первыми.

    Кнопка «Новый чат» раньше писала строку в базу сразу, до первого вопроса,
    поэтому десять нажатий подряд без вопроса оставляли десять пустых чатов в
    списке — мусор, который нечего открывать и нечем объяснить. Теперь верхний
    из пустых переиспользуется (чистый лист он и так), а остальные удаляются:
    в пустом чате нет ничего, терять нечего. Первое же сообщение делает чат
    непустым, и следующий «Новый чат» честно создаст новый."""
    try:
        return conn.execute(
            "SELECT t.id, t.subject, t.public_id, t.created_at, t.updated_at FROM agent_threads t"
            " WHERE t.user_id=? AND NOT EXISTS(SELECT 1 FROM agent_messages m WHERE m.thread_id=t.id)"
            " ORDER BY t.updated_at DESC, t.id DESC", (int(user_id),)).fetchall()
    except sqlite3.Error:
        return []


def ensure_agent_schema(conn: sqlite3.Connection) -> None:
    """Треды/сообщения агента + поле подписки (задел, подписки пока нет)."""
    key = _db_key(conn)
    if key in _AGENT_SCHEMA_DONE:
        try:
            conn.execute("SELECT id FROM agent_threads LIMIT 1")
            conn.execute("SELECT id FROM agent_messages LIMIT 1")
            cols_cached = {r["name"] for r in conn.execute("PRAGMA table_info(agent_threads)")}
            if "public_id" in cols_cached:
                return
        except sqlite3.Error:
            pass
    conn.execute("""
        CREATE TABLE IF NOT EXISTS agent_threads (
          id INTEGER PRIMARY KEY AUTOINCREMENT,
          user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
          subject TEXT NOT NULL DEFAULT 'profile_math',
          title TEXT NOT NULL DEFAULT 'Новый чат',
          created_at INTEGER NOT NULL,
          updated_at INTEGER NOT NULL,
          public_id TEXT)""")
    conn.execute("""
        CREATE TABLE IF NOT EXISTS agent_messages (
          id INTEGER PRIMARY KEY AUTOINCREMENT,
          thread_id INTEGER NOT NULL REFERENCES agent_threads(id) ON DELETE CASCADE,
          user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
          role TEXT NOT NULL CHECK(role IN ('user','assistant','tool')),
          content TEXT NOT NULL DEFAULT '',
          tool_name TEXT,
          tool_args_json TEXT NOT NULL DEFAULT '{}',
          status TEXT NOT NULL DEFAULT 'done',
          result_json TEXT NOT NULL DEFAULT '{}',
          seq INTEGER NOT NULL,
          created_at INTEGER NOT NULL)""")
    conn.execute("CREATE INDEX IF NOT EXISTS idx_agent_threads_user ON agent_threads(user_id, updated_at)")
    # Внешний идентификатор треда для ссылок: неперебираемый, в URL вместо
    # последовательного id (тот остаётся внутренним ключом базы). Только
    # латиница+цифры — без символов: в хэше они ломали бы копипаст и decode.
    try:
        tcols = {r["name"] for r in conn.execute("PRAGMA table_info(agent_threads)")}
        if tcols and "public_id" not in tcols:
            conn.execute("ALTER TABLE agent_threads ADD COLUMN public_id TEXT")
            tcols = {r["name"] for r in conn.execute("PRAGMA table_info(agent_threads)")}
        if "public_id" in (tcols or set()):
            missing = conn.execute("SELECT id FROM agent_threads WHERE public_id IS NULL OR public_id=''").fetchall()
            for mrow in missing:
                for _ in range(20):
                    cand = generate_thread_public_id()
                    exists = conn.execute("SELECT 1 FROM agent_threads WHERE public_id=?",
                                          (cand,)).fetchone()
                    if exists:
                        continue
                    try:
                        conn.execute("UPDATE agent_threads SET public_id=? WHERE id=?",
                                     (cand, int(mrow["id"])))
                        break
                    except sqlite3.Error:
                        continue
            conn.execute("CREATE UNIQUE INDEX IF NOT EXISTS idx_agent_threads_public_id"
                         " ON agent_threads(public_id)")
    except sqlite3.Error:
        pass
    try:
        cols = {r["name"] for r in conn.execute("PRAGMA table_info(agent_messages)")}
        if cols and "suggests_json" not in cols:
            conn.execute("ALTER TABLE agent_messages ADD COLUMN suggests_json TEXT NOT NULL DEFAULT '[]'")
    except sqlite3.Error:
        pass
    conn.execute("CREATE INDEX IF NOT EXISTS idx_agent_messages_thread_seq ON agent_messages(thread_id, seq)")
    conn.execute("CREATE INDEX IF NOT EXISTS idx_agent_messages_tool_status ON agent_messages(thread_id, status)")
    # Поле под будущую подписку: раздел бесплатен для всех зарегистрированных,
    # подписки в проекте пока нет. NULL/'' = бесплатный доступ.
    try:
        cols = {r["name"] for r in conn.execute("PRAGMA table_info(users)")}
        if "subscription" not in cols:
            conn.execute("ALTER TABLE users ADD COLUMN subscription TEXT")
    except sqlite3.Error:
        pass
    try:
        cols = {r["name"] for r in conn.execute("PRAGMA table_info(ai_usage)")}
        if not cols or "owner" not in cols:
            conn.execute("DROP TABLE IF EXISTS ai_usage")
            conn.execute("CREATE TABLE IF NOT EXISTS ai_usage (owner TEXT PRIMARY KEY, count INTEGER NOT NULL, timer_ms INTEGER, anchor_ms INTEGER)")
        elif "anchor_ms" not in cols:
            conn.execute("ALTER TABLE ai_usage ADD COLUMN anchor_ms INTEGER")
            conn.execute("UPDATE ai_usage SET anchor_ms=timer_ms WHERE anchor_ms IS NULL AND timer_ms IS NOT NULL")
    except sqlite3.Error:
        pass
    if "ai_usage" not in {r["name"] for r in conn.execute("SELECT name FROM sqlite_master WHERE type='table'")}:
        conn.execute("CREATE TABLE IF NOT EXISTS ai_usage (owner TEXT PRIMARY KEY, count INTEGER NOT NULL, timer_ms INTEGER, anchor_ms INTEGER)")
    conn.commit()
    _AGENT_SCHEMA_DONE.add(key)


