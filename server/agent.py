# Персональный потолок ходов, который ставит админ из карточки пользователя.
# Живёт в agent_user_limits (переживает рестарт), ровно как ai_user_limits у
# проверок сочинений. Отдельная таблица нужна потому, что ручной
# UPDATE ai_usage.count выше общего потолка доживает только до первого тика
# цепочки: _quota_catch_up делает MIN(limit, ...) и срезает грант обратно к
# EGE_AGENT_QUOTA_MAX. Без строки действует общий потолок.
AGENT_USER_LIMIT_MIN = 0
AGENT_USER_LIMIT_MAX = 1000

_AGENT_USER_LIMIT_SCHEMA_DONE: set[str] = set()


def ensure_agent_user_limit_schema(conn: sqlite3.Connection) -> None:
    key = _db_key(conn)
    if key in _AGENT_USER_LIMIT_SCHEMA_DONE:
        return
    conn.execute("""
        CREATE TABLE IF NOT EXISTS agent_user_limits (
          user_id INTEGER PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
          max_limit INTEGER NOT NULL,
          updated_at_ms INTEGER NOT NULL,
          updated_by INTEGER
        )""")
    conn.commit()
    _AGENT_USER_LIMIT_SCHEMA_DONE.add(key)


def agent_custom_limit(conn: sqlite3.Connection, user_id: int) -> int | None:
    """Персональный потолок ходов пользователя или None (действует общий)."""
    try:
        ensure_agent_user_limit_schema(conn)
        row = conn.execute("SELECT max_limit FROM agent_user_limits WHERE user_id=?",
                           (user_id,)).fetchone()
    except sqlite3.Error:
        return None
    if not row:
        return None
    try:
        value = int(row["max_limit"])
    except (TypeError, ValueError):
        return None
    if AGENT_USER_LIMIT_MIN <= value <= AGENT_USER_LIMIT_MAX:
        return value
    return None


def agent_effective_limit(conn: sqlite3.Connection, user_id: int) -> int:
    """Потолок запросов к ИИ, который реально действует на пользователя.

    База — персональный грант админа или общий EGE_AGENT_QUOTA_MAX;
    активный Plus поднимает итог до 50 (max, а не замена)."""
    custom = agent_custom_limit(conn, user_id)
    base = custom if custom is not None else agent_quota_max()
    if subscription_is_plus(conn, user_id) and _SUB is not None:
        try:
            return max(base, int(_SUB.PLUS_AGENT_LIMIT))
        except (TypeError, ValueError):
            pass
    return base


def agent_quota_status(conn: sqlite3.Connection, user_id: int,
                       fp_key: str | None = None, fp_net: str | None = None,
                       now_ms: int | None = None) -> dict:
    """Остаток ходов ИИ. Без отпечатков устройства (fp None) или для
    доверенного аккаунта — ровно старый путь по одному `agent:`-бакету.

    Для аккаунта с отпечатками остаток — минимум по своему бакету
    и котлам устройства (`ak:/an:`): ферма «вышел — новый аккаунт» упирается
    в общий котёл. Обвинение `reason: "farm_suspected"` — только когда свой
    почти полон (сам потратил не больше тика): тяжёлый сам получает обычное
    окно исчерпания. Клиент по reason показывает причину без таймера
    (время вслух не называем, чтобы не учить ферму оптимизации)."""
    ensure_agent_schema(conn)
    now_ms = int(now_ms if now_ms is not None else time.time() * 1000)
    limit = agent_effective_limit(conn, user_id)
    window_ms = agent_quota_window_ms()
    owner = _agent_owner(user_id)
    check = _agent_check_owners(conn, user_id, fp_key, fp_net, now_ms)
    device_owners = check[1:]
    if not device_owners:
        cur = conn.execute("INSERT OR IGNORE INTO ai_usage (owner, count, timer_ms) VALUES (?,?,NULL)",
                           (owner, limit))
        if cur.rowcount and _QL is not None:
            try:
                _QL.log_event(conn, owner=owner, kind="init", reason="agent:status",
                              delta=limit, count_before=None, count_after=limit,
                              limit=limit, actor=user_id, now_ms=now_ms)
            except Exception:
                pass
        _ledger_catch_up(conn, _quota_catch_up(conn, owner, now_ms, limit, window_ms),
                         owner=owner, limit=limit, reason="agent:status",
                         actor=user_id, now_ms=now_ms)
        row = conn.execute("SELECT count, timer_ms FROM ai_usage WHERE owner=?", (owner,)).fetchone()
        conn.commit()
        count = int(row["count"]) if row else limit
        timer = int(row["timer_ms"]) if row and row["timer_ms"] is not None else None
        if count >= limit:
            return {"ok": True, "limit": limit, "remaining": count,
                    "resetInSec": None, "windowSec": window_ms // 1000}
        start = timer if timer is not None else now_ms
        reset_ms = start + window_ms
        return {"ok": True, "limit": limit, "remaining": max(0, count),
                "resetInSec": max(1, (reset_ms - now_ms + 999) // 1000),
                "windowSec": window_ms // 1000}
    # Аккаунт на известном устройстве, читающий котёл: свой бакет + котлы.
    owners = [owner] + device_owners
    states: list = []
    for own in owners:
        own_limit = _agent_device_limit_for_owner(conn, own)
        cur = conn.execute("INSERT OR IGNORE INTO ai_usage (owner, count, timer_ms) VALUES (?,?,NULL)",
                           (own, own_limit))
        if cur.rowcount and _QL is not None:
            try:
                _QL.log_event(conn, owner=own, kind="init", reason="agent:status",
                              delta=own_limit, count_before=None,
                              count_after=own_limit, limit=own_limit,
                              actor=user_id, now_ms=now_ms)
            except Exception:
                pass
        _ledger_catch_up(conn, _quota_catch_up(conn, own, now_ms, own_limit, window_ms),
                         owner=own, limit=own_limit, reason="agent:status",
                         actor=user_id, now_ms=now_ms)
        row = conn.execute("SELECT count, timer_ms, anchor_ms FROM ai_usage WHERE owner=?",
                           (own,)).fetchone()
        if row:
            try:
                anchor = row["anchor_ms"]
            except (KeyError, IndexError):
                anchor = None
            states.append((int(row["count"]),
                           int(row["timer_ms"]) if row["timer_ms"] is not None else None,
                           int(anchor) if anchor is not None else None,
                           own_limit, own))
        else:
            states.append((own_limit, None, None, own_limit, own))
    conn.commit()
    projected = [(min(own_limit,
                      _CHAIN.count_at((c, t, a), now_ms, now_ms, own_limit, window_ms)),
                  t, a, own_limit, own)
                 for (c, t, a, own_limit, own) in states]
    own_rem = min(p[0] for p in projected if p[4] == owner)
    dev_rem = min([p[0] for p in projected if p[4] != owner] or [own_rem])
    remaining = min(own_rem, dev_rem)
    payload: dict = {"ok": True, "limit": limit, "remaining": remaining,
                     "windowSec": window_ms // 1000, "resetInSec": None}
    # Обвиняем в ферме, только если свой почти полон (сам потратил не больше
    # одного тика): тяжёлый сам с добитым чужими котлом получает обычное
    # окно исчерпания. Блокировка та же (остаток 0), модалка честная.
    own_lim = min([p[3] for p in projected if p[4] == owner] or [limit])
    if dev_rem < own_rem and own_rem >= own_lim - _chain_cum(1, own_lim):
        payload["reason"] = "farm_suspected"
    if remaining >= limit:
        return payload
    ticks = sorted({(t if t is not None else now_ms) + window_ms
                    for (_, t, _, own_limit, _) in projected})
    for tick in ticks:
        if tick > now_ms and min(
                min(own_limit, _CHAIN.count_at((c, t, a), tick, now_ms, own_limit, window_ms))
                for (c, t, a, own_limit, _) in states) > remaining:
            payload["resetInSec"] = max(1, (tick - now_ms + 999) // 1000)
            break
    if payload["resetInSec"] is None:
        payload["resetInSec"] = window_ms // 1000
    return payload


def agent_quota_reserve(conn: sqlite3.Connection, user_id: int,
                        fp_key: str | None = None, fp_net: str | None = None,
                        *, reason: str = "agent:turn",
                        actor: int | None = None) -> bool:
    """Списать один запрос к ИИ. True — списано, False — квота пуста.

    Трата греет и котлы устройства (`ak:/an:`) ВСЕГДА, когда отпечатки
    известны — даже у давнего аккаунта и даже у Plus/гранта: иначе старый
    основной аккаунт исчерпывал бы только свой бакет, а свежая ферма рядом
    видела бы холодный котёл и получала полный лимит (живая дыра).
    Блокирует котёл только свежий аккаунт без админского гранта; давний
    своим остатком не делится с соседями по компьютеру — его резерв при
    пустом котле всё равно проходит (котёл при этом не уходит в минус)."""
    ensure_agent_schema(conn)
    now_ms = int(time.time() * 1000)
    limit = agent_effective_limit(conn, user_id)
    window_ms = agent_quota_window_ms()
    owner = _agent_owner(user_id)
    exempt = _agent_device_exempt(conn, user_id)
    check = _agent_check_owners(conn, user_id, fp_key, fp_net, now_ms)
    # Требует успеха только ЧИТАЕМОЕ (свой + котлы из остатка): пустой
    # ненаблюдаемый котёл (сеть у давнего) резерв не роняет.
    must_set = set(check)
    gate = len(check) > 1
    device_owners = _agent_device_owners(fp_key, fp_net) if not exempt else []
    try:
        spent_by = int(user_id) if actor is None else int(actor)
    except (TypeError, ValueError):
        spent_by = int(user_id)
    for own in [owner] + device_owners:
        own_limit = _agent_device_limit_for_owner(conn, own)
        cur = conn.execute("INSERT OR IGNORE INTO ai_usage (owner, count, timer_ms) VALUES (?,?,NULL)",
                           (own, own_limit))
        if cur.rowcount and _QL is not None:
            try:
                _QL.log_event(conn, owner=own, kind="init", reason=reason,
                              delta=own_limit, count_before=None,
                              count_after=own_limit, limit=own_limit,
                              actor=spent_by, now_ms=now_ms)
            except Exception:
                pass
        _ledger_catch_up(conn, _quota_catch_up(conn, own, now_ms, own_limit, window_ms),
                         owner=own, limit=own_limit, reason=reason,
                         actor=spent_by, now_ms=now_ms)
    # Остаток до списания — для журнала трат (один SELECT на всех,
    # бакетов не больше трёх).
    before: dict = {}
    try:
        q = ",".join("?" * (len(device_owners) + 1))
        for brow in conn.execute(f"SELECT owner, count FROM ai_usage WHERE owner IN ({q})",
                                 tuple([owner] + device_owners)):
            try:
                before[str(brow["owner"])] = int(brow["count"])
            except (TypeError, ValueError, KeyError, IndexError):
                pass
    except sqlite3.Error:
        pass
    def _log_spend(own: str, own_limit: int) -> None:
        if _QL is None:
            return
        try:
            was = before.get(own)
            _QL.log_event(conn, owner=own, kind="spend", reason=reason,
                          delta=-1, count_before=was,
                          count_after=(was - 1 if was is not None else None),
                          limit=own_limit, actor=spent_by, now_ms=now_ms)
        except Exception:
            pass
    cur = conn.execute("""
        UPDATE ai_usage SET count = count - 1,
          timer_ms = CASE WHEN timer_ms IS NULL THEN ? ELSE timer_ms END,
          anchor_ms = CASE WHEN timer_ms IS NULL THEN ?
                           WHEN anchor_ms IS NULL THEN timer_ms
                           ELSE anchor_ms END
        WHERE owner = ? AND count > 0""", (now_ms, now_ms, owner))
    if cur.rowcount == 0:
        conn.rollback()
        return False
    _log_spend(owner, limit)
    if gate:
        for own in device_owners:
            cur = conn.execute("UPDATE ai_usage SET count = count - 1,"
                               " timer_ms = CASE WHEN timer_ms IS NULL THEN ? ELSE timer_ms END,"
                               " anchor_ms = CASE WHEN timer_ms IS NULL THEN ?"
                               " WHEN anchor_ms IS NULL THEN timer_ms ELSE anchor_ms END"
                               " WHERE owner = ? AND count > 0",
                               (now_ms, now_ms, own))
            if cur.rowcount == 0 and own in must_set:
                conn.rollback()
                return False
            if cur.rowcount:
                _log_spend(own, _agent_device_limit_for_owner(conn, own))
    else:
        # Plus/грант (читают только своё, см. _agent_check_owners): котёл
        # греем в меру (пустой не трогаем и не блокируем им свой резерв) —
        # чтобы возврат ниже не рисовал жетон из воздуха, пустой котёл
        # возврату не подлежит (см. refund).
        for own in device_owners:
            cur = conn.execute("UPDATE ai_usage SET count = count - 1,"
                               " timer_ms = CASE WHEN timer_ms IS NULL THEN ? ELSE timer_ms END,"
                               " anchor_ms = CASE WHEN timer_ms IS NULL THEN ?"
                               " WHEN anchor_ms IS NULL THEN timer_ms ELSE anchor_ms END"
                               " WHERE owner = ? AND count > 0",
                               (now_ms, now_ms, own))
            if cur.rowcount:
                _log_spend(own, _agent_device_limit_for_owner(conn, own))
    conn.commit()
    return True


def agent_quota_refund_many(conn: sqlite3.Connection, user_id: int, n: int,
                            fp_key: str | None = None, fp_net: str | None = None,
                            *, reason: str = "agent:refund") -> None:
    """Вернуть n запросов к ИИ (для отката целого хода при неуспехе).

    По одному за раз через agent_quota_refund: таймер полного кармана гасится
    ровно тогда, когда карман снова полон, а кап MIN(limit, ...) держит гранты.
    n<=0 — no-op. Овердрафтные (бесплатные) вызовы сюда не попадают: их
    возвращать нечего, итог хода и так ровно 0. Отпечатки — те же, что у
    резервов хода: котлы устройства возвращаются вместе со своим бакетом."""
    try:
        count = max(0, int(n))
    except (TypeError, ValueError):
        return
    for _ in range(min(count, MAX_TOOL_STEPS + MAX_TOOL_RETRIES + 4)):
        agent_quota_refund(conn, int(user_id), fp_key, fp_net, reason=reason)


def agent_quota_refund(conn: sqlite3.Connection, user_id: int,
                       fp_key: str | None = None, fp_net: str | None = None,
                       *, reason: str = "agent:refund") -> None:
    # Возврат зеркален резерву, но намеренно проще него: резерв давнего
    # аккаунта пустой котёл не трогает (WHERE count>0), а возврат каплет
    # +1 с MIN-капом. Разница — at most один лишний жетон котла за каждый
    # неуспешный ход на горячем устройстве; ходы падают редко, жетон
    # растворяется в цепочке. Точный учёт «что именно списалось» потребовал
    # бы таскать списки owners через весь цикл хода — цена выше выгоды.
    ensure_agent_schema(conn)
    limit = agent_effective_limit(conn, user_id)
    owner = _agent_owner(user_id)
    owners = [owner] if _agent_device_exempt(conn, user_id) else [owner] + _agent_device_owners(fp_key, fp_net)
    try:
        spent_by = int(user_id)
    except (TypeError, ValueError):
        spent_by = 0
    # Остаток до возврата — для журнала (один SELECT на всех).
    before: dict = {}
    if _QL is not None and owners:
        try:
            q = ",".join("?" * len(owners))
            for brow in conn.execute(f"SELECT owner, count FROM ai_usage WHERE owner IN ({q})",
                                     tuple(owners)):
                try:
                    before[str(brow["owner"])] = int(brow["count"])
                except (TypeError, ValueError, KeyError, IndexError):
                    pass
        except sqlite3.Error:
            pass
    try:
        for own in owners:
            own_limit = _agent_device_limit_for_owner(conn, own)
            conn.execute("""
                UPDATE ai_usage SET count = MIN(?, count + 1),
                  timer_ms = CASE WHEN count + 1 >= ? THEN NULL ELSE timer_ms END,
                  anchor_ms = CASE WHEN count + 1 >= ? THEN NULL ELSE anchor_ms END
                WHERE owner = ?""", (own_limit, own_limit, own_limit, own))
            if _QL is not None:
                try:
                    was = before.get(own)
                    now_count = min(own_limit, was + 1) if was is not None else None
                    _QL.log_event(conn, owner=own, kind="refund", reason=reason,
                                  delta=1, count_before=was,
                                  count_after=now_count, limit=own_limit,
                                  actor=spent_by, now_ms=int(time.time() * 1000))
                except Exception:
                    pass
        conn.commit()
    except sqlite3.Error:
        try:
            conn.rollback()
        except sqlite3.Error:
            pass


