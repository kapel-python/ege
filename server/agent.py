def turn_context(conn: sqlite3.Connection, user_id: int, subject: str) -> str:
    """Стартовый блок хода: имя, предмет простыми словами, компактный прогноз.

    Экономит целый круг модели: раньше «какой у меня предмет» и «как меня
    зовут» требовали вызова fold_web(op="profile"), а «какой прогноз» —
    ещё и fold_web(op="forecast"). Теперь это лежит в system с первого
    токена. Прогноз считается тем же _compute_forecast (копейки локального
    SQL, без провайдера) и актуален на начало хода; детали (ошибки,
    попытки, разборы) по-прежнему только инструментами. Не бросает:
    при любой проблеме отдаёт то, что собралось (хоть пусто).
    """
    lines = ["КОНТЕКСТ ХОДА (данные сервера на начало хода)."]
    try:
        name = None
        try:
            row = conn.execute("SELECT name FROM users WHERE id=?",
                               (int(user_id),)).fetchone()
            name = str(row["name"] or "").strip() if row else ""
        except (sqlite3.Error, TypeError, ValueError, KeyError, IndexError):
            name = ""
        if name:
            lines.append(f"Ученик: «{name[:40]}».")
        title = subject_title(subject)
        if title:
            lines.append(f"Текущий предмет: {title}.")
        try:
            fc = _compute_forecast(conn, int(user_id), str(subject or ""))
        except Exception:
            fc = {}
        if isinstance(fc, dict) and fc.get("available"):
            try:
                mid = int(fc.get("mid", 0))
                low = int(fc.get("low", 0))
                high = int(fc.get("high", 0))
            except (TypeError, ValueError):
                mid = low = high = 0
            unit = "из 100" if str(fc.get("unit") or "") == "percent" else "баллов"
            gains = [str(g.get("name") or g.get("skillId") or "").strip()
                     for g in (fc.get("topGains") or []) if isinstance(g, dict)]
            gains = [g for g in gains if g][:3]
            line = f"Прогноз: сейчас ~{mid} {unit}, разброс {low}–{high}."
            if gains:
                line += " Что подтянуть: " + ", ".join(f"«{g[:60]}»" for g in gains) + "."
            lines.append(line)
        lines.append("Числа и факты выше — от сервера, их можно называть сразу "
                     "без вызова инструментов; детали (ошибки, попытки, разборы) "
                     "добери инструментами.")
    except Exception:
        pass
    return "\n".join(lines)


def turn_system(conn: sqlite3.Connection, user_id: int, subject: str) -> str:
    """Системный промпт хода: общий AGENT_SYSTEM + стартовый контекст."""
    try:
        ctx = turn_context(conn, user_id, subject)
    except Exception:
        ctx = ""
    if not ctx.strip():
        return AGENT_SYSTEM
    return AGENT_SYSTEM + "\n" + ctx


# ---------------------------------------------------------------------------
# Обещание вместо вызова инструмента
#
# Живой случай: «посмотри мой профиль» → модель отвечает «Сейчас посмотрю твой
# профиль» и НЕ зовёт fold_web. Ученик видит болтовню вместо данных, а ход
# считается успешным. Это не ошибка формата (текст без вызовов — легальный
# ответ), поэтому раньше такой ответ ещё и кэшировался.
#
# Лечится тремя шагами: (1) промпт запрещает обещать вместо вызова, (2) цикл
# ловит обещание и переспрашивает ОДИН раз жёстко, (3) если модель упрямится —
# сервер сам зовёт очевидный инструмент по вопросу и просит ответ по данным.
# Последний шаг делает отказ невозможным: данные придут из базы в любом случае.
# ---------------------------------------------------------------------------

def _tool_payload(data: dict, cap: int = 4000) -> str:
    """JSON результата инструмента в контекст модели — ВСЕГДА валидный.

    Раньше здесь стояло `json.dumps(data)[:4000]`: обрезка по символам режет
    JSON посреди объекта, и модель получала нечитаемый хвост (замерено на живой
    базе: fold_web(op=attempts, limit=50) = 7973 симв. → в модель уходило 4000 с
    обрывом `..."taskId": "n01`). Теперь режем ПО ЭЛЕМЕНТАМ списка и честно
    говорим, что показано не всё.
    """
    try:
        blob = json.dumps(data, ensure_ascii=False)
    except (TypeError, ValueError):
        return json.dumps({"error": "результат не сериализуется"}, ensure_ascii=False)
    if len(blob) <= cap:
        return blob
    # Длинные списки укорачиваем поштучно, пока не влезем.
    trimmed = dict(data)
    # Разбор одного сочинения: criteria лежат ВНУТРИ essay, резать их пополам
    # нельзя (нужны все К1-К10) — ужимаем комментарии и отрывок, а не строки.
    ess = trimmed.get("essay")
    if isinstance(ess, dict) and isinstance(ess.get("criteria"), list):
        ess = dict(ess)
        for comment_cap, excerpt_cap, keep_improve in ((100, 500, False), (50, 200, False)):
            crits = [dict(c) for c in ess.get("criteria") or [] if isinstance(c, dict)]
            for c in crits:
                c["comment"] = str(c.get("comment") or "")[:comment_cap]
            ess["criteria"] = crits
            if not keep_improve:
                ess.pop("whatToImprove", None)
            if isinstance(ess.get("excerpt"), str):
                ess["excerpt"] = ess["excerpt"][:excerpt_cap]
                ess["excerptTruncated"] = True
            trimmed["essay"] = ess
            trimmed["truncated"] = {"field": "essay.criteria",
                                    "note": "комментарии и отрывок ужаты по размеру"}
            try:
                if len(json.dumps(trimmed, ensure_ascii=False)) <= cap:
                    return json.dumps(trimmed, ensure_ascii=False)
            except (TypeError, ValueError):
                break
    for key in ("attempts", "last", "skills", "days", "criteria", "bySkill", "essays",
                "periods"):
        seq = trimmed.get(key)
        if not isinstance(seq, list) or len(seq) < 2:
            continue
        cut = list(seq)
        while len(cut) > 1:
            cut = cut[:len(cut) // 2]
            trimmed[key] = cut
            trimmed["truncated"] = {"field": key, "shown": len(cut), "total": len(seq),
                                    "note": "показана часть списка"}
            try:
                if len(json.dumps(trimmed, ensure_ascii=False)) <= cap:
                    return json.dumps(trimmed, ensure_ascii=False)
            except (TypeError, ValueError):
                break
    # Не список — режем строковые поля, но метку обрезки ставим ДО обрезки.
    trimmed = dict(data)
    trimmed["truncated"] = {"note": "результат обрезан по размеру"}
    blob = json.dumps(trimmed, ensure_ascii=False)
    if len(blob) <= cap:
        return blob
    return json.dumps({"error": "результат слишком большой, попроси меньше",
                       "hint": "уменьши limit"}, ensure_ascii=False)


def _emit_live_step(on_step, step: dict) -> None:
    """Живой шаг подписчику (сервер публикует его в снимок треда). Не бросает:
    подписчик чужой, а ход ронять нельзя."""
    if on_step is None:
        return
    try:
        on_step(step)
    except Exception:
        pass


def run_cycle(conn: sqlite3.Connection, user_id: int, subject: str, messages: list,
              chat_fn, *, deadline: float | None = None, on_step=None) -> tuple[list, str | None, dict | None]:
    """Один проход модель↔инструменты. Возвращает (steps, final, pending).

    steps — [{name, args, label, kind}] для ленты; final — текст ответа либо
    None, если ход встал на подтверждение; pending — {tool, args, proposal}
    для confirm при действии, иначе None. Бросает AI* при сбое модели.

    chat_fn(messages, tools, budget) — budget это остаток времени хода в
    секундах: им вызов ограничивает себя, иначе 90-секундный потолок держался
    бы только «между шагами», а один зависший вызов провайдера растягивал ход
    ещё на EGE_AI_TIMEOUT_SEC (45 с) сверх него.

    on_step(step) — колбэк живого шага: зовётся сразу после выполнения КАЖДОГО
    read-инструмента (шаг уже с label и результатом), а не в конце всего хода.
    Сервер публикует его в live-снимок треда, и клиент дорисовывает ленту по
    мере прихода — лоадер шага живёт ровно столько, сколько модель реально
    думала, а не фиксированные ~2 с постфактум-анимации. Не бросает: исключение
    подписчика глушится, ход продолжается.
    """
    deadline = deadline if deadline is not None else (time.monotonic() + TURN_TIMEOUT_SEC)
    steps: list = []
    failed = 0
    for _ in range(MAX_TOOL_STEPS + MAX_TOOL_RETRIES + 1):
        budget = deadline - time.monotonic()
        if budget <= TURN_CALL_FLOOR_SEC:
            # Бюджета не осталось. Если что-то уже собрано — отдаём это (шаги
            # видны в ленте, текст честный), потому что отказ с потерей всего
            # хода хуже ответа «не успел». Нечего показать — 502 с бесплатным
            # повтором (жетон вернётся в finally).
            if steps:
                return steps, _summarize(chat_fn, messages), None
            raise TimeoutError("ход превысил 90 секунд")
        parsed = chat_fn(messages, AGENT_TOOLS, budget)
        text = parsed.get("text")
        calls = parsed.get("tool_calls") or []
        if len(calls) > 1:
            # Один запрос — один инструмент (правило 2b промпта): пачку в одном
            # ответе модель иногда всё равно даёт («вызови все» → 3 вызова
            # разом, живой случай 29.09). Берём первый, остальные отбрасываем —
            # модель переспросит нужное следующим шагом, уже видя результат
            # первого. Пачку целиком выполнять нельзя: зависимые вызовы
            # (task_get с id из find_topics) корректны только по очереди, а
            # остановка после первого шага экономит целый круг модели.
            calls = calls[:1]
        # Модель часто пишет реплику («Сейчас соберу…») и зовёт инструменты в
        # одном сообщении. Это не пол-ответа: вызовы главнее, реплику
        # переигрываем в том же assistant-сообщении (см. parse_tool_message).
        preamble = parsed.get("preamble")
        if text is not None and not calls:
            # Текст без вызовов — обычный финал: модель решила ответить сама,
            # и сервер её не поправляет, ничего не зовёт за неё и не
            # переспрашивает. Что модель сказала (включая «сейчас посмотрю»
            # без вызова и «инструмента нет»), то ученик и видит.
            # Пустой текст — не ответ: уходит в _summarize (ответ модели по
            # собранному или честный отказ исключением), а не в пустую карточку.
            # Непустой возвращается как есть, БЕЗ реза длины: потолок режет
            # провайдер (AI_REPLY_MAX), а рез до вырезания ```suggest оторвал
            # бы кнопки-продолжения у длинного ответа.
            if str(text).strip():
                return steps, str(text), None
            return steps, _summarize(chat_fn, messages), None
        if not calls:
            # Парсер ai.py такое уже отбраковал; страховка от чужого chat_fn.
            # Нечего показать — честный отказ (502 с возвратом жетона),
            # а не переспрос: модель уже имела слово.
            if steps:
                return steps, _summarize(chat_fn, messages), None
            raise ValueError("пустой ответ модели")
        if len(steps) + len(calls) > MAX_TOOL_STEPS:
            # Потолок кодом: длинный цикл обрываем ответом по собранным данным,
            # а не ошибкой — ученик звал «вызови всё», и отказ тут обиднее ответа.
            return steps, _summarize(chat_fn, messages), None
        for call in calls:
            name = str(call.get("name") or "")
            call_args = call.get("arguments") if isinstance(call.get("arguments"), dict) else {}
            call_id = str(call.get("id") or "")
            if name in ACTION_TOOLS:
                try:
                    proposal = propose_action(conn, user_id, subject, name, call_args)
                except ValueError as exc:
                    # Действие с неверными аргументами (выдуманный errorId,
                    # цель не из шкалы) больше не убивает ход: ошибка уходит
                    # обратно в контекст, модель чинит вызов и повторяет.
                    # Пара assistant+tool обязательна для провайдера, поэтому
                    # пишем её ДО продолжения цикла, иначе следующий запрос
                    # придёт с «висящим» вызовом без ответа.
                    failed += 1
                    messages.append({"role": "assistant", "content": preamble or None,
                                     "tool_calls": [{"id": call_id, "type": "function",
                                                     "function": {"name": name,
                                                                  "arguments": json.dumps(call_args, ensure_ascii=False)}}]})
                    messages.append({"role": "tool", "tool_call_id": call_id,
                                     "content": json.dumps(_tool_failure(conn, subject, name, call_args, exc),
                                                           ensure_ascii=False)[:4000]})
                    preamble = None
                    if failed >= MAX_TOOL_RETRIES:
                        return steps, _summarize(chat_fn, messages), None
                    continue
                label = proposal.get("label") or describe_step(name, call_args)
                steps.append({"name": name, "args": call_args, "label": label, "kind": "action",
                              "status": "needs_confirm", "call_id": call_id, "proposal": proposal})
                # final=None: ход встал на подтверждение, и всё, что ученик должен
                # узнать, живёт в подписи шага — она теперь человеческая
                # («Отмечаю разобранной ошибку по теме «…»»), а не «по заданию
                # n02_p1». Отдельный assistant-текст здесь не хранится и клиент
                # его не рисует, поэтому выдумывать второй носитель смысла нет.
                return steps, None, {"tool": name, "args": call_args,
                                     "proposal": proposal, "call_id": call_id}
            try:
                data = execute_read_tool(conn, user_id, subject, name, call_args)
            except ValueError as exc:
                # ГЛАВНОЕ: неверный аргумент — это ответ инструмента модели, а
                # не приговор ходу. Раньше отсюда летел AgentInputError → 400
                # ученику: живой прогон 20 сценариев — 6 ходов из 20 умерли так
                # («уроки по скиллу не найдены», «задание не найдено», «цель не
                # из шкалы»), причём все вопросы были обычными. Теперь модель
                # получает ошибку с подсказками (что за id существуют) и
                # пробует снова; лимит — MAX_TOOL_RETRIES, дальше честный ответ
                # по тому, что уже собрано.
                failed += 1
                messages.append({"role": "assistant", "content": preamble or None,
                                 "tool_calls": [{"id": call_id, "type": "function",
                                                 "function": {"name": name,
                                                              "arguments": json.dumps(call_args, ensure_ascii=False)}}]})
                messages.append({"role": "tool", "tool_call_id": call_id,
                                 "content": json.dumps(_tool_failure(conn, subject, name, call_args, exc),
                                                       ensure_ascii=False)[:4000]})
                preamble = None
                if failed >= MAX_TOOL_RETRIES:
                    return steps, _summarize(chat_fn, messages), None
                continue
            label = describe_step(name, call_args, data)
            steps.append({"name": name, "args": call_args, "label": label, "kind": "read",
                          "status": "done", "call_id": call_id, "result": data})
            _emit_live_step(on_step, {"name": name, "args": call_args, "label": label,
                                      "kind": "read", "status": "done", "result": data})
            messages.append({"role": "assistant", "content": preamble or None,
                             "tool_calls": [{"id": call_id, "type": "function",
                                              "function": {"name": name, "arguments": json.dumps(call_args, ensure_ascii=False)}}]})
            messages.append({"role": "tool", "tool_call_id": call_id,
                             "content": _tool_payload(data)})
            # Реплика принадлежит первому вызову пачки: дальше в пачке она уже
            # была бы переигровкой того же сообщения.
            preamble = None
        # Продолжаем цикл: модель решает дальше с результатами инструментов.
    return steps, _summarize(chat_fn, messages), None


# ---------------------------------------------------------------------------
# Кнопки-продолжения после ответа
#
# Модель дописывает в конец ответа служебный блок ```suggest с вариантами
# «что спросить дальше»: label (текст кнопки, любой — хоть «я умный») и ask
# (готовый вопрос от лица ученика, уходит на сервер как обычный ход). Блок
# вырезается из текста и в ленту не попадает; клиент рисует кнопки с этими
# словами. Формат блока строгий (иначе не разобрать), содержимое — свободное.
#
# Если модель блок не дала (или дала мусор) — кнопок нет (пустой список), а не
# дежурный набор: кнопки — слова модели, заглушка хуже отсутствия. Хранятся они
# в agent_messages.suggests_json рядом с ответом, поэтому история показывает те
# же кнопки, что ученик видел вживую.
# ---------------------------------------------------------------------------
SUGGEST_BLOCK_RE = re.compile(r"```\s*suggest\s*\n?(.*?)\n?```", re.DOTALL | re.IGNORECASE)
# Блок БЕЗ закрывающей ограды: ответ провайдера обрезался по лимиту, и ```` ```suggest ````
# остался висеть открытым. Основной regex требует закрытия и такой блок не
# находит — служебный блок целиком попадал в ответ ученика (живой случай:
# «Извини, последняя кнопка кривая — вот исправленный блок:» + обрывок JSON).
# Отрезаем от открытой ограды до конца ответа.
SUGGEST_OPEN_RE = re.compile(r"```\s*suggest\b[^\n]*\n?.*\Z", re.DOTALL | re.IGNORECASE)
MAX_SUGGESTIONS = 3
# Потолок «вопроса» кнопки: короткий, иначе кнопка перестаёт быть кнопкой.
SUGGEST_ASK_MAX = 160


def _suggest_item(raw) -> dict | None:
    """Одна кнопка: {"label": str, "ask": str} либо None, если мусор."""
    if not isinstance(raw, dict):
        return None
    label = " ".join(str(raw.get("label") or raw.get("title") or "").split())[:40]
    ask = " ".join(str(raw.get("ask") or raw.get("text") or raw.get("question") or "").split())
    ask = ask[:SUGGEST_ASK_MAX]
    if not ask or len(ask) < 3:
        return None
    return {"label": label or ask[:28], "ask": ask}


def split_suggestions(text: str) -> tuple[str, list]:
    """Вырезать блок ```suggest из ответа. Возвращает (чистый текст, варианты).

    Блок может быть JSON-массивом (как просит промпт) либо построчным списком
    «label | ask» — модели иногда отвечают проще, и терять кнопки из-за этого
    нельзя. Всё непонятное молча отбрасываем: текст ответа важнее.
    """
    body = str(text or "")
    items: list = []
    # ВСЕ закрытые блоки, а не только первый: модель может дать два (правка
    # «кнопки кривые» — как в живом чате), и раньше второй блок оставался в
    # тексте ответа ученику целиком. Смещения берём у списка совпадений и режем
    # С КОНЦА: при поочерёдной правке строки ранние смещения «уезжают».
    matches = list(SUGGEST_BLOCK_RE.finditer(body))
    inners = [m.group(1).strip() for m in matches]
    for m in reversed(matches):
        body = (body[:m.start()] + body[m.end():]).strip()
    for inner in inners:
        parsed = None
        try:
            parsed = json.loads(inner)
        except (ValueError, TypeError):
            parsed = None
        if isinstance(parsed, dict):
            parsed = parsed.get("suggestions") or parsed.get("items") or []
        if isinstance(parsed, list):
            for raw in parsed:
                item = _suggest_item(raw)
                if item:
                    items.append(item)
        else:
            # Построчный режим — «label | ask». Строка без разделителя это
            # проза модели, а не подсказка: кнопка с целым предложением
            # выглядит мусором, поэтому её просто не берём (ниже подставится
            # запасной набор).
            for line in inner.splitlines():
                line = line.strip().lstrip("-*0123456789. ").strip()
                if not line or "|" not in line:
                    continue
                label, _, ask = line.partition("|")
                item = _suggest_item({"label": label.strip(), "ask": (ask or label).strip()})
                if item:
                    items.append(item)
    # Дубли по ask (модель любит повторить одну мысль двумя кнопками).
    seen: set[str] = set()
    unique: list = []
    for item in items:
        key = item["ask"].lower()
        if key in seen:
            continue
        seen.add(key)
        unique.append(item)
    # Страховка: СЛУЖЕБНЫЙ блок не должен попасть в ленту ни при каком разборе —
    # даже обрезанный ответ провайдера. Кнопок в этом случае не будет (правильно:
    # блок не разобран), но ученик не увидит «```suggest» и извинения модели.
    if "```suggest" in body.lower():
        body = SUGGEST_OPEN_RE.sub("", body).strip()
        unique = []
    return body.strip(), unique[:MAX_SUGGESTIONS]


# Запасных «шаблонных» кнопок нет осознанно: кнопки — это слова модели, а не
# форма. Нет блока от модели — нет кнопок (пустой список), а не дежурный набор:
# заглушка, не имеющая отношения к ответу, хуже её отсутствия. Настоящие кнопки
# хранятся в agent_messages.suggests_json рядом с ответом, поэтому история
# показывает те же слова модели, а не подстановку по последнему шагу.


def _summarize(chat_fn, messages: list) -> str:
    """Финал по потолку шагов: один вызов БЕЗ инструментов — короткий ответ по
    уже собранным данным.

    Ничего не теряем: жетон хода уже потрачен, данные на руках. Время хода
    кончилось, модель снова полезла в инструменты или сломалась — тогда
    честный отказ исключением (сервер отдаст 502 с бесплатным повтором и
    вернёт жетон). Шаблонного текста здесь нет осознанно: говорить с
    учеником имеет право только модель.

    Окно у этого вызова своё (TURN_SUMMARY_EXTRA_SEC): бюджет хода к этому
    моменту обычно исчерпан, а финалу нужны секунды — иначе честный ответ
    подменялся бы отказом ровно тогда, когда всё уже собрано.
    """
    deadline = time.monotonic() + TURN_SUMMARY_EXTRA_SEC
    for attempt in range(2):
        budget = deadline - time.monotonic()
        if budget <= TURN_CALL_FLOOR_SEC:
            break
        # Последнее сообщение истории — результат инструмента, а вызова без
        # tools такой хвост у провайдеров не ждут: закрываем его короткой
        # репликой ученика («дальше не лезь, ответь»), а не молчанием.
        ask = list(messages) + [{"role": "user",
                                 "content": "Данных достаточно. Ответь коротко по тому, "
                                            "что уже собрано, и не вызывай новые инструменты."}]
        if attempt:
            # Второй раз — жёстче: модель уже проигнорировала просьбу.
            ask.append({"role": "user",
                        "content": "Без вызовов инструментов. Только текст ответа."})
        try:
            parsed = chat_fn(ask, [], budget) or {}
        except Exception:  # noqa: BLE001 — ответ без модели лучше 502
            break
        text = parsed.get("text")
        if text and not (parsed.get("tool_calls") or []):
            return str(text)[:AGENT_REPLY_MAX]
    raise TimeoutError("модель не вернула финал хода")
