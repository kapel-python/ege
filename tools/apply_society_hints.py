def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry", action="store_true")
    args = ap.parse_args()

    data = json.loads(CATALOG.read_text(encoding="utf-8"))
    tasks = data["tasks"]

    changed = 0
    unknown = sorted({t.get("skill") for t in tasks if t.get("skill") not in TOPIC_HINTS})
    for t in tasks:
        hints = TOPIC_HINTS.get(t.get("skill"))
        if not hints:
            continue
        if t.get("hints") != hints or t.get("hint") != hints[0]:
            changed += 1
        t["hint"] = hints[0]
        t["hints"] = list(hints)

    # Главное место — метаданные темы: фронт (topicHintLevels) берёт три
    # универсальные подсказки именно из skill.metadata.hints во всех потоках,
    # кроме уроков. Заданию оставлены те же три как запасной вариант.
    skills_done = 0
    for skill in data.get("skills", []):
        hints = TOPIC_HINTS.get(skill.get("id"))
        if not hints:
            continue
        meta = skill.get("metadata") if isinstance(skill.get("metadata"), dict) else {}
        meta["hints"] = list(hints)
        skill["metadata"] = meta
        skills_done += 1

    # Уроки держат собственные подсказки, но движок берёт их только когда их
    # ровно три (hintLevelsFor). У 34 шагов общества их было две — движок
    # молча подставлял заглушку вместо авторской. Дополняем третьей
    # универсальной подсказкой темы, свои две не трогаем.
    padded = 0
    for lesson in data.get("lessons", []):
        topic = TOPIC_HINTS.get(lesson.get("skill"))
        if not topic:
            continue
        for step in lesson.get("steps", []):
            if step.get("type") != "ACTION":
                continue
            hs = list(step.get("hints") or [])
            if len(hs) == 2:
                step["hints"] = hs + [topic[2]]
                padded += 1

    print(f"тем: {len(TOPIC_HINTS)}, заданий обновлено: {changed}, "
          f"тем с metadata.hints: {skills_done}, шагов уроков дополнено: {padded}")
    if unknown:
        print(f"ВНИМАНИЕ: темы без универсальных подсказок: {unknown}")

    if args.dry:
        return 0
    CATALOG.write_text(json.dumps(data, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print("записано")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())