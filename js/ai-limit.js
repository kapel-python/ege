var AI_LIMIT_FALLBACK = 5;

function aiLimitPlural(n, one, few, many) {
  var m10 = Math.abs(Number(n) || 0) % 10, m100 = Math.abs(Number(n) || 0) % 100;
  if (m10 === 1 && m100 !== 11) return one;
  if (m10 >= 2 && m10 <= 4 && (m100 < 10 || m100 >= 20)) return few;
  return many;
}
