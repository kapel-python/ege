/* ============================================================
   Интерактивные (визуальные) уроки — БЕТА. Точка входа с фронта.

   Источник правды — БЭКЕНД (каталог предмета, ключ "interactiveLessons"):
   сервер хранит уроки в таблице ilessons, отдаёт мету в bootstrap
   (summary + full) и полные сцены срезом /api/catalog-ilessons.
   Фронт читает их через DataAPI.ilessons()/ilesson()/ilessonsBySkill().
   Здесь — только навигация и шаблон авторской записи каталога.

   Как добавить новый визуальный урок на любую тему:
   1. В файл каталога предмета (server/catalog*.json) добавь запись
      в массив "interactiveLessons" (создай, если нет) — см.
      INTERACTIVE_LESSON_CATALOG_TEMPLATE ниже.
      skill — id темы (skill.id), сцены — 4–8 штук, 1 идея = 1 сцена.
   2. Перезапусти сервер (install_catalog подхватит запись).
   3. Готово: кнопка «Интерактивный урок» в модалке темы, секция
      в «Тренировке» и роут #/ilesson/<skillId> подхватят урок сами.
      Пустой scenes или отсутствие записи = красивая заглушка.

   Формат сцены: { title?, text, visual? }.
   visual — опционально: { kind: "svg"|"html", svg|html: "<...>" }.
   HTML/SVG вставляется как есть: источник доверенный (наш каталог),
   чужой HTML сюда не вставлять. Текст сцены идёт через mathText,
   поэтому формулы KaTeX работают как в обычных уроках.
   ============================================================ */

/* Точка входа из модалки темы и секции «Тренировки».
   Отдельный параметр (skillId), а не lessonId: визуальный урок привязан
   к ТЕМЕ, а не к записи классического каталога. Сам роут решит, показать
   урок или заглушку. */
function openInteractiveLesson(skillId) {
  const id = String(skillId == null ? "" : skillId).trim();
  if (!id) return;
  try { if (typeof closeModal === "function") closeModal(); } catch (_) {}
  try {
    if (typeof go === "function") { go("ilesson", id); return; }
  } catch (_) {}
  try { location.hash = "#/ilesson/" + encodeURIComponent(id); } catch (_) {}
}

